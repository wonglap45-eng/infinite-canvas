import type { ReferenceImage } from "@/types/image";

export type ImageReferenceMode = "preserve-product" | "redesign-label" | "secondary-product";

export function imageReferenceLabel(index: number) {
    return `图片${index + 1}`;
}

export function buildImageReferencePromptText(prompt: string, references: ReferenceImage[], mode: ImageReferenceMode = "preserve-product") {
    const text = prompt.trim();
    if (!references.length) return text;
    const labels = references.map((_, index) => imageReferenceLabel(index));
    const executionRules =
        mode === "redesign-label"
            ? `1. 参考图片只用于确认用户产品的物理包装和真实信息，不是需要复刻的标签设计稿。保留产品品类、数量、袋型/瓶型/盒型、物理轮廓、尺寸比例、封口、易撕口、底部结构和真实材质，不能换成其他商品。
2. 保留用户产品真实品牌、Logo 身份、产品名称、规格和图片中能够确认的事实信息；这些内容只作为重新排版的事实素材，不保留它们在旧标签中的字号、位置、颜色、层级或组合方式。不能复制其他品牌信息，也不能虚构功效、认证、成分或参数。
3. 系统提供给你的参考图已经被主动去除标签细节，只是一张包装结构参考图。图中的模糊灰块、残余明暗和低清轮廓不代表旧标签设计，不得把它们还原成原来的色带、图标、文字排布或装饰。
4. 生成前先把包装可印刷区域视为空白印刷基材，从零建立新的标签视觉系统。旧标签背景、色带、波浪、分区、图标行、装饰图形、文字位置、信息层级、配色比例、字体组合、徽章、边框、纹理和表面效果都不是保留对象。提示词规定的新核心图形、版面骨架、阅读顺序、色彩关系和工艺表现必须完整取代旧标签；保留产品身份不等于保留旧标签样式。
5. 最终结果必须仍是同一件真实产品和同一物理包装，但缩小到画布缩略图尺寸时也应能一眼看出标签已经重新设计。若结果仍可被误认为原图、只改了少量文字、颜色或局部装饰，则视为失败，必须继续重做而不是返回近似原图。
6. 只修改包装可印刷区域，不在商品外部添加文字、Logo、图标、道具或装饰；背景、机位、构图与光影按照用户提示词执行。`
            : mode === "secondary-product"
              ? `1. 参考图片是用户的 B 产品身份图，只用于锁定最终画面中的唯一商品主体，不是整张副图的构图底稿。必须保留该产品的真实品牌、Logo、包装类型、物理轮廓、尺寸比例、颜色、标签位置和能够确认的原有文字，不能换成其他商品。
2. 参考图片原有的背景、留白、画幅、产品位置、大小、机位和接地阴影不是保留对象。请按照用户提示词重新搭建整张副图的背景、构图、产品位置、视觉动线、信息区域、道具关系、氛围和光影，让同一件 B 产品进入提示词规定的新商业画面。
3. 用户提示词来自对 A 副图的视觉分析。只迁移其中描述的场景机制、构图关系、信息组织、材质氛围、装饰元素和观看顺序；A 图中的竞品产品、品牌、Logo、产品名、包装文字、卖点、规格和事实信息都不能进入最终图片。
4. 商品必须保持真实完整，不改包装标签、不重排包装文字、不改颜色、不改变瓶型/袋型/盒型，不生成相似但不同的替代包装。商品外部的标题、卖点和图形只能使用用户明确提供或 B 产品图中确实可确认的信息；不确定的内容留空，不得虚构。
5. 最终成片必须明显执行提示词规定的副图表达，而不是把 B 产品原图原位复制后只换一点背景。缩小到缩略图时，应能看出新的场景关系、构图机制或信息表达已经成立，同时仍能一眼确认是同一个 B 产品。`
              : `1. 参考图片是用户上传的产品主体，不是可选灵感图。最终生成图必须以参考图片中的产品为唯一产品主体。
2. 必须保留参考产品的品类、数量、瓶型/盒型/袋型、包装比例、品牌识别、Logo 和图片中能够确认的真实文字事实。
3. 如果用户提示词明确要求重新设计包装标签或可印刷区域，应保留产品身份与真实事实，但允许并应当改变标签版式、图形、颜色、文字层级和视觉风格；不要把旧标签样式错误地当成不可修改的产品结构。
4. 如果用户没有要求包装设计变化，则保持参考产品的主要颜色、标签位置、核心图案、配件关系和可识别外观。
5. 下方提示词如果来自竞品图反推，只能迁移构图、画面比例、背景、光影、道具关系、商业视觉机制和质量标准，不能复制竞品品牌、包装文字、产品形状、卖点或事实信息。
6. 不要把参考产品替换成另一件商品，不要虚构不存在的标签事实，不要改变品牌归属，不要生成与参考图片无关的商品。`;
    return `参考图片编号：${labels.join("、")}。

重要执行规则：
${executionRules}

用户提示词：
${text}`;
}
